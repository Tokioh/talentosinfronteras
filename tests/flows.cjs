'use strict';
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const {createServer} = require('../scripts/serve.cjs');
(async () => {
  const server = createServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_PATH || undefined});
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const url = `http://127.0.0.1:${server.address().port}`;
    const route = async hash => {await page.goto(url + '/#' + hash); await page.locator('h1').waitFor();};
    await route('vacantes');
    assert.equal(await page.locator('.job').count(), 6);
    await page.locator('[data-save]').first().click();
    assert.equal(await page.evaluate(() => document.activeElement.dataset.save), 'v1');
    await page.locator('#only-saved').click();
    assert.equal(await page.locator('.job').count(), 1);
    await page.locator('#only-saved').click();
    await page.locator('#query').fill('zzzz-no-existe');
    await page.locator('#search-form button').click();
    await page.locator('#reset-filters').click();
    assert.equal(await page.locator('.job').count(), 6);
    await route('perfil');
    await page.locator('[name=name]').fill('<img src=x onerror=alert(1)>');
    await page.locator('[name=skills]').fill('  ,  ');
    await page.locator('#profile-form button').first().click();
    assert.match(await page.locator('#status').textContent(), /al menos una competencia/);
    await page.locator('[name=skills]').fill('HTML, CSS, JavaScript, Accesibilidad');
    await page.locator('#profile-form button').first().click();
    await page.reload();
    assert.equal(await page.locator('[name=skills]').inputValue(), 'HTML, CSS, JavaScript, Accesibilidad');
    assert.equal(await page.locator('#main img').count(), 0);
    // Persistence and removal of a small audio fixture (not a playback-quality test).
    await page.locator('#media').setInputFiles({name:'prueba.wav',mimeType:'audio/wav',buffer:Buffer.from('RIFF-test-fixture')});
    await page.locator('#transcript').fill('Presentación de prueba en texto.');
    await page.locator('#media-form button').first().click();
    await page.locator('#media-preview audio').waitFor();
    await page.reload();
    await page.locator('#media-preview audio').waitFor();
    assert.equal(await page.locator('#transcript').inputValue(), 'Presentación de prueba en texto.');
    await page.locator('#remove-media').click();
    await page.waitForFunction(() => !document.querySelector('#media-preview audio'));
    assert.equal(await page.locator('#transcript').inputValue(), '');
    await route('ajustes');
    await page.locator('[name=enabled-0]').check();
    await page.locator('[name=notes-0]').fill('Pausas acordadas');
    await page.locator('[name=visibility-0]').selectOption('application');
    await page.locator('[name=enabled-1]').check();
    await page.locator('#adjust-form button').click();
    await route('vacantes');
    await page.locator('[data-detail=v1]').click();
    assert.equal(await page.getByRole('dialog', {name:'Especialista en atención al cliente'}).count(), 1);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'detail-title');
    assert.equal(await page.locator('[name=share]').count(), 1);
    await page.locator('[name=share]').check();
    await page.locator('#apply-form button').first().click();
    const applications = await page.evaluate(() => JSON.parse(localStorage.getItem('tsb-v1')).applications);
    assert.equal(applications.length, 1);
    assert.equal(applications[0].adjustments.length, 1);
    assert.equal(applications[0].adjustments[0].notes, 'Pausas acordadas');
    await route('postulaciones');
    await page.locator('[data-message]').click();
    await page.locator('[name=body]').fill('Consulta de prueba');
    await page.locator('#message-form button').click();
    assert.equal(await page.locator('.message').count(), 1);
    await route('postulaciones');
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('[data-withdraw]').click();
    assert.equal(await page.locator('[data-withdraw]').count(),0);
    await route('revision');
    await page.locator('[name=body]').fill('Revisar esta recomendación');
    await page.locator('#review-form button').click();
    const downloadEvent = page.waitForEvent('download');
    await page.locator('[data-export-request]').click();
    assert.match((await downloadEvent).suggestedFilename(), /^REV-.*\.txt$/);
    await route('empresa');
    for (const [name,value] of Object.entries({company:'Empresa prueba',title:'Puesto prueba',city:'Manta',salary:'USD 600 / mes',functions:'Atender consultas',skills:'Comunicación',environment:'Acceso sin escalones'})) await page.locator(`[name=${name}]`).fill(value);
    await page.locator('#employer-form button').click();
    await page.locator('.job').filter({hasText:'Puesto prueba'}).waitFor();
    await page.locator('.job').filter({hasText:'Puesto prueba'}).locator('[data-save]').click();
    await route('empresa');
    page.once('dialog', dialog => dialog.accept());
    await page.locator('[data-delete-job]').click();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('tsb-v1')).saved.some(id=>id.startsWith('local-'))), false);
    await page.setViewportSize({width:375,height:900});
    await page.locator('nav [href="#empresa"]').waitFor({state:'visible'});
    // Malformed but valid JSON must not break any route.
    await page.evaluate(() => localStorage.setItem('tsb-v1', JSON.stringify({profile:{skills:42},jobs:[null,{}],applications:[{}],adjustments:null,messages:'invalid',requests:[null],saved:{}})));
    await page.reload();
    for (const hash of ['vacantes','perfil','ajustes','postulaciones','mensajes','revision','empresa']) {
      await route(hash);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `Desbordamiento en ${hash}`);
    }
    await page.evaluate(() => localStorage.setItem('tsb-v1', '{broken'));
    await page.reload();
    await page.locator('h1').waitFor();
    // A failed write must not be reported as persisted.
    await page.evaluate(() => {Storage.prototype.setItem = () => {throw Error('blocked');};});
    await route('perfil');
    await page.locator('#profile-form button').first().click();
    assert.match(await page.locator('#status').textContent(), /solo estarán disponibles durante esta sesión/);
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#clear-data').click();
    await page.waitForFunction(() => localStorage.getItem('tsb-v1') === null);
    assert.equal(await page.evaluate(() => localStorage.getItem('tsb-v1')), null);
    assert.deepEqual(errors, []);
    console.log('PASS: búsqueda, guardados, foco, perfil, ajustes privados, postulación, mensajes, revisión, empresas, móvil, datos corruptos y almacenamiento bloqueado.');
  } finally {
    await browser?.close();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(error => {console.error(error); process.exitCode=1;});
